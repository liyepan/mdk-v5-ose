#include "core/Lang.h"

#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QProcess>
#include <QStandardPaths>
#include <QTemporaryFile>
#include <QTimer>

namespace {

QString native(const QString& path)
{
#ifdef Q_OS_WIN
    return QDir::toNativeSeparators(path);
#else
    return path;
#endif
}

// Qt 5.15 才有 QProcess::splitCommand，这里自己拆一下（支持双引号包起来的参数）
QStringList splitCommand(const QString& command)
{
    QStringList parts;
    QString current;
    bool inQuotes = false;

    for (const QChar c : command) {
        if (c == QLatin1Char('"')) {
            inQuotes = !inQuotes;
            continue;
        }
        if (!inQuotes && c.isSpace()) {
            if (!current.isEmpty()) {
                parts << current;
                current.clear();
            }
            continue;
        }
        current += c;
    }
    if (!current.isEmpty())
        parts << current;
    return parts;
}

} // namespace

Flasher::Flasher(QObject* parent)
    : QObject(parent)
{
}

QStringList Flasher::toolNames(const QString& backend)
{
    if (backend == QLatin1String("jlink"))
        return { QStringLiteral("JLink.exe"), QStringLiteral("JLinkExe"), QStringLiteral("JLink") };
    if (backend == QLatin1String("openocd"))
        return { QStringLiteral("openocd"), QStringLiteral("openocd.exe") };
    if (backend == QLatin1String("pyocd"))
        return { QStringLiteral("pyocd"), QStringLiteral("pyocd.exe") };
    return {};
}

QString Flasher::detectTool(const QString& backend)
{
    if (backend == QLatin1String("custom"))
        return QString();

    for (const QString& name : toolNames(backend)) {
        const QString found = QStandardPaths::findExecutable(name);
        if (!found.isEmpty())
            return found;
    }

#ifdef Q_OS_WIN
    // J-Link 默认装在 Program Files 下，PATH 里通常没有
    if (backend == QLatin1String("jlink")) {
        const QStringList candidates = {
            QStringLiteral("C:/Program Files/SEGGER/JLink/JLink.exe"),
            QStringLiteral("C:/Program Files (x86)/SEGGER/JLink/JLink.exe"),
            QStringLiteral("C:/Program Files/SEGGER/JLink_V*/JLink.exe"),
        };
        for (const QString& pattern : candidates) {
            if (!pattern.contains(QLatin1Char('*'))) {
                if (QFileInfo::exists(pattern))
                    return pattern;
                continue;
            }
            const QFileInfo info(pattern);
            QDir dir(info.absolutePath() + QLatin1Char('/') + info.fileName().section(QLatin1Char('/'), 0, 0));
            const QFileInfoList dirs = QDir(QFileInfo(pattern).absolutePath())
                                           .entryInfoList(QStringList{ QStringLiteral("JLink_V*") },
                                                          QDir::Dirs);
            for (const QFileInfo& d : dirs) {
                const QString candidate = d.absoluteFilePath() + QStringLiteral("/JLink.exe");
                if (QFileInfo::exists(candidate))
                    return candidate;
            }
        }
    }
#endif

    return QString();
}

bool Flasher::isRunning() const
{
    return m_process && m_process->state() != QProcess::NotRunning;
}

void Flasher::cancel()
{
    if (m_process && m_process->state() != QProcess::NotRunning) {
        m_process->kill();
        fail(Lang::t("Download cancelled"));
    }
}

void Flasher::start(const FlashRequest& request)
{
    if (isRunning())
        return;
    m_finished = false;
    m_errorText.clear();

    const FlashConfig& config = request.config;
    if (request.filePath.isEmpty() || !QFileInfo::exists(request.filePath)) {
        fail(QStringLiteral("找不到要烧写的文件：%1").arg(request.filePath));
        return;
    }

    QString program;
    QStringList args;
    QString workingDir = request.workDir;

    if (config.backend == QLatin1String("jlink")) {
        program = config.toolPath.isEmpty() ? detectTool(config.backend) : config.toolPath;
        if (program.isEmpty()) {
            fail(QStringLiteral("没找到 J-Link Commander（JLink.exe）。"
                                "请在 Tools -> Flash Download Settings 里指定路径。"));
            return;
        }

        // J-Link Commander 靠脚本干活：烧完复位、跑起来、退出
        QTemporaryFile script(QDir::tempPath() + QStringLiteral("/mdk-ose-XXXXXX.jlink"));
        if (!script.open()) {
            fail(QStringLiteral("创建临时脚本失败"));
            return;
        }
        QString body;
        body += QStringLiteral("// generated by mdk-v5-ose\n");
        if (request.binary) {
            body += QStringLiteral("loadbin %1, 0x%2\n")
                        .arg(native(request.filePath))
                        .arg(request.baseAddress, 0, 16);
            // verifybin 只认裸二进制；对 .hex 用它 J-Link 会直接报错
            if (config.verify)
                body += QStringLiteral("verifybin %1, 0x%2\n")
                            .arg(native(request.filePath))
                            .arg(request.baseAddress, 0, 16);
        } else {
            // .hex / .elf 用 loadfile，J-Link 自己会校验校验和
            body += QStringLiteral("loadfile %1\n").arg(native(request.filePath));
        }
        if (config.resetAfter) {
            body += QStringLiteral("r\n");
            body += QStringLiteral("g\n");
        }
        body += QStringLiteral("exit\n");
        script.write(body.toUtf8());
        script.flush();
        m_scriptPath = script.fileName();
        script.setAutoRemove(false);

        args << QStringLiteral("-device") << (request.device.isEmpty() ? QStringLiteral("Cortex-M3") : request.device)
             << QStringLiteral("-if") << config.interface
             << QStringLiteral("-speed") << QString::number(config.speed)
             << QStringLiteral("-autoconnect") << QStringLiteral("1")
             << QStringLiteral("-ExitOnError") << QStringLiteral("1")
             << QStringLiteral("-CommandFile") << native(m_scriptPath);
        workingDir = QFileInfo(program).absolutePath();
    } else if (config.backend == QLatin1String("openocd")) {
        program = config.toolPath.isEmpty() ? detectTool(config.backend) : config.toolPath;
        if (program.isEmpty()) {
            fail(QStringLiteral("没找到 openocd，请指定路径"));
            return;
        }
        args << QStringLiteral("-f") << config.openocdInterface;
        if (!config.openocdTarget.isEmpty())
            args << QStringLiteral("-f") << config.openocdTarget;
        QString cmd = QStringLiteral("program %1").arg(native(request.filePath));
        if (config.verify)
            cmd += QStringLiteral(" verify");
        if (config.resetAfter)
            cmd += QStringLiteral(" reset");
        cmd += QStringLiteral(" exit");
        args << QStringLiteral("-c") << cmd;
    } else if (config.backend == QLatin1String("pyocd")) {
        program = config.toolPath.isEmpty() ? detectTool(config.backend) : config.toolPath;
        if (program.isEmpty()) {
            fail(QStringLiteral("没找到 pyocd，请指定路径"));
            return;
        }
        args << QStringLiteral("flash")
             << QStringLiteral("-t") << request.device.toLower()
             << native(request.filePath);
    } else {
        // custom：用户自己写命令，占位符替换后再按空格切
        if (config.customCommand.trimmed().isEmpty()) {
            fail(QStringLiteral("自定义烧写命令是空的"));
            return;
        }
        QString command = config.customCommand;
        command.replace(QStringLiteral("{file}"), native(request.filePath));
        command.replace(QStringLiteral("{device}"), request.device);
        command.replace(QStringLiteral("{interface}"), config.interface);
        command.replace(QStringLiteral("{speed}"), QString::number(config.speed));
        command.replace(QStringLiteral("{addr}"), QStringLiteral("0x%1").arg(request.baseAddress, 0, 16));
        const QStringList parts = splitCommand(command);
        if (parts.isEmpty()) {
            fail(QStringLiteral("自定义烧写命令解析失败"));
            return;
        }
        program = parts.first();
        args = parts.mid(1);
    }

    emit output(QStringLiteral("> %1 %2").arg(program, args.join(QLatin1Char(' '))));

    m_process = new QProcess(this);
    m_process->setWorkingDirectory(workingDir);
    m_process->setProcessChannelMode(QProcess::SeparateChannels);
    connect(m_process, &QProcess::readyReadStandardOutput, this, &Flasher::handleStdout);
    connect(m_process, &QProcess::readyReadStandardError, this, &Flasher::handleStderr);
    connect(m_process, QOverload<int, QProcess::ExitStatus>::of(&QProcess::finished), this,
            [this](int code, QProcess::ExitStatus status) {
                if (m_finished)
                    return;
                if (status == QProcess::CrashExit) {
                    fail(QStringLiteral("烧写工具异常退出"));
                    return;
                }
                if (code != 0) {
                    QString detail = m_errorText.trimmed();
                    if (detail.isEmpty())
                        detail = QStringLiteral("退出码 %1").arg(code);
                    fail(detail);
                    return;
                }
                succeed();
            });
    connect(m_process, &QProcess::errorOccurred, this, [this](QProcess::ProcessError error) {
        if (m_finished)
            return;
        if (error == QProcess::FailedToStart)
            fail(QStringLiteral("烧写工具启动失败（路径对吗？）"));
    });

    m_process->start(program, args);
    if (!m_process->waitForStarted(3000)) {
        fail(QStringLiteral("烧写工具启动失败：%1").arg(m_process->errorString()));
        return;
    }

    // 烧大工程可能久一点，但卡死不能无限等
    m_timeout = new QTimer(this);
    m_timeout->setSingleShot(true);
    connect(m_timeout, &QTimer::timeout, this, [this]() {
        if (m_finished)
            return;
        if (m_process)
            m_process->kill();
        fail(QStringLiteral("烧写超时"));
    });
    m_timeout->start(180000);
}

void Flasher::handleStdout()
{
    if (!m_process)
        return;
    const QString text = QString::fromLocal8Bit(m_process->readAllStandardOutput());
    for (const QString& raw : text.split(QLatin1Char('\n'))) {
        const QString line = raw.trimmed();
        if (line.isEmpty())
            continue;
        emit output(line);
        if (line.contains(QLatin1String("Error"), Qt::CaseInsensitive))
            m_errorText += line + QLatin1Char('\n');
    }
}

void Flasher::handleStderr()
{
    if (!m_process)
        return;
    const QString text = QString::fromLocal8Bit(m_process->readAllStandardError());
    for (const QString& raw : text.split(QLatin1Char('\n'))) {
        const QString line = raw.trimmed();
        if (line.isEmpty())
            continue;
        emit output(line);
        m_errorText += line + QLatin1Char('\n');
    }
}

void Flasher::fail(const QString& error)
{
    if (m_finished)
        return;
    m_finished = true;

    if (m_timeout)
        m_timeout->stop();
    if (m_process && m_process->state() != QProcess::NotRunning) {
        m_process->kill();
        m_process->waitForFinished(1000);
    }
    if (!m_scriptPath.isEmpty()) {
        QFile::remove(m_scriptPath);
        m_scriptPath.clear();
    }

    emit finished(false, error);
}

void Flasher::succeed()
{
    if (m_finished)
        return;
    m_finished = true;

    if (m_timeout)
        m_timeout->stop();
    if (!m_scriptPath.isEmpty()) {
        QFile::remove(m_scriptPath);
        m_scriptPath.clear();
    }

    emit finished(true, QString());
}
